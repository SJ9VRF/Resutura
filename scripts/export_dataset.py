from pathlib import Path
import json, gzip, hashlib, io

ROOT=Path(__file__).resolve().parents[1]
RUN=ROOT/'runs'/'effect_semantics_suite.json.gz'
OUT=ROOT/'artifacts'/'dataset'
SCENARIO_FAULTS={
  'compensable_misdirection':['redirect_publish_target'],
  'ambiguous_commit':['ambiguous_publish_timeout'],
  'concurrent_change_plus_misdirection':['concurrent_valid_publication','redirect_publish_target'],
  'noncompensatable_misdirection':['redirect_publish_noncompensatable'],
}

def split_for(task_id):
    # Public diagnostic split; not a hidden benchmark split.
    n=int(hashlib.sha256(task_id.encode()).hexdigest()[:8],16)%10
    return 'dev' if n<2 else 'test'

def main():
    with gzip.open(RUN,'rt',encoding='utf-8') as rf:
        data=json.load(rf)
    OUT.mkdir(parents=True,exist_ok=True)
    tasks={}
    trajectory_count=0
    with (OUT/'trajectories.jsonl.gz').open('wb') as raw:
      with gzip.GzipFile(filename='',mode='wb',fileobj=raw,mtime=0) as gz:
       with io.TextIOWrapper(gz,encoding='utf-8',newline='\n') as f:
        for scenario,methods in data['scenarios'].items():
            for method,payload in methods.items():
                for run in payload['runs']:
                    task_id=run['task_id']; seed=run['seed']
                    tasks[(scenario,task_id)]={
                      'benchmark_item_id':f'{scenario}:{task_id}', 'task_id':task_id,
                      'scenario':scenario,'faults':SCENARIO_FAULTS[scenario],
                      'seed':seed,'split':split_for(task_id),
                      'note':'Task content is deterministically generated by make_task; see source for exact generator.'
                    }
                    row={'scenario':scenario,'method':method,'split':split_for(task_id),**run}
                    f.write(json.dumps(row,sort_keys=True)+'\n'); trajectory_count+=1
    with (OUT/'tasks.jsonl').open('w',encoding='utf-8') as f:
        for row in sorted(tasks.values(),key=lambda x:x['benchmark_item_id']):f.write(json.dumps(row,sort_keys=True)+'\n')
    schema={
      'dataset_name':'Resutura Mechanism Traces','version':'1.0.0',
      'task_records':len(tasks),'trajectory_records':trajectory_count,
      'files':{
        'tasks.jsonl':'One row per scenario/task pair.',
        'trajectories.jsonl.gz':'One raw trajectory per method/scenario/task run.',
      },
      'trajectory_required_fields':['scenario','method','split','run_id','task_id','seed','success','steps','final_observation'],
      'caveat':'Deterministic synthetic mechanism dataset; not natural user data and not a frontier-model benchmark.'
    }
    (OUT/'schema.json').write_text(json.dumps(schema,indent=2,sort_keys=True))
    splits={'dev':0,'test':0}
    for r in tasks.values():splits[r['split']]+=1
    manifest={'version':'1.0.0','task_count':len(tasks),'trajectory_count':trajectory_count,'task_split_counts':splits,
              'source_run':'runs/effect_semantics_suite.json.gz','source_sha256':hashlib.sha256(RUN.read_bytes()).hexdigest(),
              'public_split_warning':'These are public diagnostic splits, not hidden evaluation data.'}
    (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2,sort_keys=True))
    print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
